from typing import List, Literal, Tuple

from datasets import Dataset
import numpy as np
from opentslm.prompt.text_time_series_prompt import TextTimeSeriesPrompt
from opentslm.time_series_datasets.esa_mission1.esa_mission1_cot_loader import load_esa_mission1_cot_splits
from opentslm.time_series_datasets.QADataset import QADataset


class ESAMission1CoTQADataset(QADataset):
    """Six-hour ESA-AD Mission1 subsystem_5 telemetry windows, nominal vs. anomalous, with a
    chain-of-thought rationale generated by a separate pipeline step (see scripts/generate_cot.py
    in the zurich-hackathon project)."""

    def __init__(
        self,
        split: Literal["train", "test", "validation"],
        EOS_TOKEN: str,
        format_sample_str: bool = False,
        time_series_format_function=None,
    ):
        super().__init__(split, EOS_TOKEN, format_sample_str, time_series_format_function)

    def _load_splits(self) -> Tuple[Dataset, Dataset, Dataset]:
        return load_esa_mission1_cot_splits()

    def _get_answer(self, row) -> str:
        return row["answer"]

    def _get_pre_prompt(self, row) -> str:
        return f"""
        You are an ESA spacecraft operations engineer reviewing six hours of satellite telemetry from
        Mission1, subsystem_5, {row["channel"]}. Your task is to determine whether this window is
        nominal or anomalous.

        Instructions:
        - Analyze the time series without presuming a particular label.
        - Reason step by step about level, trend, noise, spikes, drift, and gaps.
        - Write your reasoning as a single, natural paragraph. Do not use bullet points, numbered
          steps, or section headings.
        - Do not state the label until the very last sentence.
        """

    def _get_post_prompt(self, _row) -> str:
        return """Possible labels are:
        nominal, anomalous

        - Please now write your rationale. Make sure that your last word is the answer. You MUST end your response with "Answer: """

    def _get_text_time_series_prompt_list(self, row) -> List[TextTimeSeriesPrompt]:
        series = np.array(row["values"], dtype=np.float32)
        mean = float(np.mean(series))
        std = max(float(np.std(series)), 1e-6)
        normalized = (series - mean) / std
        text = f"This is telemetry from {row['channel']}, it has mean {mean:.4f} and std {std:.4f}:"
        return [TextTimeSeriesPrompt(text, normalized.tolist())]

    def _format_sample(self, row):
        sample = super()._format_sample(row)
        sample["label"] = row["label"]
        sample["channel"] = row["channel"]
        return sample

    @staticmethod
    def get_labels() -> List[str]:
        return ["nominal", "anomalous"]
