"""Connector for ``esa/mission1-subsystem5``: ESA-AD Mission1 subsystem_5 anomaly windows.

The source is a local extract of the ESA Anomaly Dataset (ESA-AD, Zenodo record 12528696), not a
Hub or PhysioNet source, so this subclasses :class:`BaseConnector` directly. It reads six channel
files (``channel_41`` through ``channel_46``, ESA-ADB's own lightweight subset) plus ``labels.csv``
and ``anomaly_types.csv`` from a directory named by the ``ESA_MISSION1_DIR`` environment variable.

Each labeled ``Anomaly`` or ``Rare Event`` interval on those channels becomes one six-hour
"anomalous" window (one hour of context before the labeled start, five hours after), paired with
one "nominal" window sampled from the same channel and split half, clear of every labeled interval
on that channel. This avoids training on the raw dataset's ~1.8% anomaly imbalance. The split
follows the ESA-ADB benchmark's own train/test boundary at 2007-01-01.

``Communication Gap`` and ``Invalid Segment`` intervals are excluded from the anomalous/nominal
pairing entirely: per the ESA-AD paper's own category definitions (Kotowski et al. 2024,
Supplementary Table 1), both are "not directly related to known anomalies" (missing or invalid
data, not a signal anomaly) and the paper's own alarming policy says neither should be flagged by
a detector. They are still used to guard nominal-window sampling, though, so a "nominal" window
never accidentally overlaps missing or invalid data.

Channel timestamps in the raw pickles are timezone-naive, while ``labels.csv`` timestamps carry a
``Z`` (UTC) suffix. Both name the same wall clock, so this connector converts every timestamp to
naive UTC-equivalent microseconds before comparing or slicing; nothing here claims a real timezone.

Each record also carries two periodicity scores (``window_periodicity``, over the record's own
6-hour window, and ``context_periodicity``, over the surrounding 24 hours): mean and standard
deviation say nothing about whether a channel is oscillating, and several subsystem_5 channels are
periodic in some windows and not others (see :func:`_periodicity_score`). Comparing the two -- "this
channel is normally periodic, but not in this window" -- is a signal mean/std cannot express.

Each record also carries ``minutes_since_command`` when a priority>=2 telecommand executed within
the preceding 6 hours of the window's reference point (the labeled start for an anomalous window,
or the matching offset into a nominal one): a causal (backward-only) search, since a telecommand
firing after an event cannot have caused it. A commanded Rare Event should follow a telecommand
almost immediately -- empirically, over half of Rare Events on these channels are preceded by one
within 5 minutes, versus essentially none of the Anomalies -- so this is a strong, nearly free
signal for exactly the distinction ESA's own category definitions draw. Absent when
``telecommands.csv``/``telecommands/`` aren't found under the source directory, or no qualifying
command fired in the lookback window.

Chain-of-thought rationales are generated by a separate pipeline step, not this connector. When the
``ESA_MISSION1_SUBSYSTEM5_RATIONALES`` environment variable names a JSON file mapping window id to
rationale text, :meth:`ESAMission1Subsystem5Connector.convert` attaches it as the task's answer and
``rationale``. Without one, the answer falls back to a bare ``"Answer: <label>"`` so the pipeline
never blocks on chain-of-thought generation.
"""

from dataclasses import dataclass
import json
import os
from pathlib import Path
from types import ModuleType
from typing import TYPE_CHECKING
import zipfile

import numpy as np

from timenet.connectors import BaseConnector
from timenet.dataset import TimeFDataset, TimeSeries
from timenet.errors import TimeFValidationError
from timenet.types import Annotation, AnswerTask, DataSource, TimeSeriesSpec, ureg


if TYPE_CHECKING:
    import pandas as pd


_CHANNELS: tuple[str, ...] = tuple(f"channel_{i}" for i in range(41, 47))
_EXCLUDED_CATEGORIES = frozenset({"Communication Gap", "Invalid Segment"})
"""Categories that are "not directly related to known anomalies" per the ESA-AD paper's own
definitions (missing or invalid data, not a signal anomaly). Excluded from the anomalous/nominal
pairing; still used to guard nominal-window sampling."""
_WINDOW_BEFORE_US = 3_600_000_000  # 1 hour of context before a labeled interval's start
_WINDOW_AFTER_US = 18_000_000_000  # 5 hours after: 6 hours total
_WINDOW_LEN_US = _WINDOW_BEFORE_US + _WINDOW_AFTER_US
_OVERLAP_GUARD_US = 3_600_000_000  # 1 hour buffer kept clear of every labeled interval
_CONTEXT_LEN_US = 86_400_000_000  # 24h context window for the periodicity baseline, centered on
# the same point as the 6h window (window_start + 3h): 9h before window_start, 15h after.
_CONTEXT_BEFORE_US = 32_400_000_000
_MIN_PERIODICITY_POINTS = 50  # below this, an autocorrelation peak is unreliable; omit the score
_ZERO_VARIANCE_TOLERANCE = 1e-9  # below this stdev, treat the sequence as constant
_TELECOMMAND_MIN_PRIORITY = 2  # empirically the cleanest threshold; see module docstring
_TELECOMMAND_LOOKBACK_US = 21_600_000_000  # 6h: causal match rate is already >75% within this
_TEST_SPLIT_AT = "2007-01-01"  # the ESA-ADB benchmark's own train/test boundary
_SEED = 20260912  # fixed seed keeps nominal-window sampling deterministic across builds
_MAX_NOMINAL_ATTEMPTS = 200

_DEFAULT_SOURCE_DIR = "/var/tmp/hrm/zurich-hackathon/data/ESA-Mission1"  # noqa: S108 (not a tempfile call: the shared hackathon data path, overridable via ESA_MISSION1_DIR)
_SOURCE_DIR_ENV = "ESA_MISSION1_DIR"
_RATIONALES_ENV = "ESA_MISSION1_SUBSYSTEM5_RATIONALES"

_QUESTION = "Is this window nominal or anomalous, and why?"

_SOURCE = DataSource(
    data_source_type="real",
    name="ESA Anomaly Dataset (ESA-AD) Mission1",
    provider="Airbus Defence and Space / KP Labs / ESA ESOC",
)


def _spec_for(channel: str) -> TimeSeriesSpec:
    """Build the value spec for one telemetry channel.

    Args:
        channel: The channel name, for example ``"channel_41"``.

    Returns:
        A dimensionless float32 spec tagged with the channel name, so records across channels stay
        distinguishable in the derived schema.
    """
    return TimeSeriesSpec(
        spec_type=f"esa_mission1_{channel}",
        name=f"ESA Mission1 {channel}",
        unit_value=ureg.dimensionless,
        data_source=_SOURCE,
    )


@dataclass(frozen=True, kw_only=True)
class ESAWindowRef:
    """A lightweight reference to one six-hour window, before its values are read.

    :meth:`ESAMission1Subsystem5Connector.download` builds these from ``labels.csv`` and a random,
    non-overlapping sample per channel; :meth:`ESAMission1Subsystem5Connector.convert` reads each
    window's values from ``channel_path``.
    """

    window_id: str
    """Stable id for this window: the record id and the base of every annotation/task id on it."""
    channel: str
    """The channel this window comes from, for example ``"channel_41"``."""
    channel_path: Path
    """Path to the channel's extracted pickle file."""
    window_start_us: int
    """Window start, in naive UTC-equivalent Unix microseconds (see module docstring)."""
    label: str
    """``"anomalous"`` or ``"nominal"``."""
    category: str | None
    """The anomaly's ``Category`` (``Anomaly`` or ``Rare Event`` -- ``Communication Gap`` and
    ``Invalid Segment`` are excluded from pairing, see module docstring), or ``None`` for a
    nominal window."""
    anomaly_class: str | None
    """The anomaly's ``Class``, or ``None`` for a nominal window."""
    anomaly_id: str | None
    """The ``labels.csv`` row id this window pairs with, shared by its anomalous and nominal
    windows."""
    split: str
    """``"train"`` or ``"test"``, by the ESA-ADB benchmark's 2007-01-01 boundary."""


def _source_dir() -> Path:
    """Resolve the local ESA-AD Mission1 directory from the environment.

    Returns:
        The configured directory, or the shared hackathon default if unset.
    """
    return Path(os.environ.get(_SOURCE_DIR_ENV, _DEFAULT_SOURCE_DIR))


def _import_pandas() -> ModuleType:
    """Import pandas lazily, with a clear error if it is missing.

    Returns:
        The imported ``pandas`` module.

    Raises:
        ImportError: If pandas, declared in this connector's requirements.txt, is missing.
    """
    try:
        import pandas as pd  # noqa: PLC0415
    except ImportError as exc:
        raise ImportError(
            "reading ESA-AD Mission1 needs pandas, declared in this connector's requirements.txt. "
            "Run the build without --no-isolation, or install it yourself"
        ) from exc
    return pd


def _extract_channel(source_dir: Path, cache_dir: Path, channel: str) -> Path:
    """Extract one channel's pickle from its zip into ``cache_dir``, if not already there.

    Args:
        source_dir: The local ESA-AD Mission1 directory.
        cache_dir: The connector's cache directory for this build.
        channel: The channel to extract, for example ``"channel_41"``.

    Returns:
        Path to the extracted pickle file.
    """
    dest = cache_dir / channel
    if not dest.exists():
        with zipfile.ZipFile(source_dir / "channels" / f"{channel}.zip") as archive:
            archive.extract(channel, path=cache_dir)
    return dest


def _load_labels(source_dir: Path) -> "pd.DataFrame":
    """Load and join ``labels.csv`` with ``anomaly_types.csv``, filtered to the subsystem_5 channels.

    Converts ``StartTime``/``EndTime`` to naive UTC-equivalent timestamps, matching the channel
    pickles (see module docstring).

    Args:
        source_dir: The local ESA-AD Mission1 directory.

    Returns:
        One row per labeled interval on a subsystem_5 channel, with its ``Category`` and ``Class``.
    """
    pd = _import_pandas()
    labels = pd.read_csv(source_dir / "labels.csv", parse_dates=["StartTime", "EndTime"])
    labels["StartTime"] = labels["StartTime"].dt.tz_convert(None)
    labels["EndTime"] = labels["EndTime"].dt.tz_convert(None)
    anomaly_types = pd.read_csv(source_dir / "anomaly_types.csv")
    labels = labels[labels["Channel"].isin(_CHANNELS)]
    return labels.merge(anomaly_types, on="ID", how="left")


def _split_for(start_time: "pd.Timestamp") -> str:
    """Classify a timestamp by the ESA-ADB benchmark's own train/test boundary.

    Args:
        start_time: A naive UTC-equivalent timestamp to classify.

    Returns:
        ``"train"`` if before 2007-01-01, else ``"test"``.
    """
    return "train" if start_time < _import_pandas().Timestamp(_TEST_SPLIT_AT) else "test"


def _sample_nominal_start_us(
    rng: np.random.Generator,
    channel_span: tuple[int, int],
    guarded_intervals_us: list[tuple[int, int]],
) -> int:
    """Sample a six-hour window start clear of every guarded interval on this channel.

    Args:
        rng: The connector's seeded random generator.
        channel_span: The channel's ``(first_us, last_us)`` timestamp range.
        guarded_intervals_us: Every labeled interval on this channel, in naive UTC-equivalent
            microseconds, each already padded by :data:`_OVERLAP_GUARD_US`.

    Returns:
        A window start, in naive UTC-equivalent microseconds, whose six-hour window overlaps no
        guarded interval.

    Raises:
        TimeFValidationError: If no non-overlapping window turns up within the sampling budget.
    """
    first_us, last_us = channel_span
    latest_start = last_us - _WINDOW_LEN_US
    for _ in range(_MAX_NOMINAL_ATTEMPTS):
        start_us = int(rng.integers(first_us, latest_start))
        end_us = start_us + _WINDOW_LEN_US
        if not any(start_us < g_end and end_us > g_start for g_start, g_end in guarded_intervals_us):
            return start_us
    raise TimeFValidationError(
        f"could not find a nominal window clear of labeled intervals in {_MAX_NOMINAL_ATTEMPTS} attempts"
    )


def _load_rationales() -> dict[str, str]:
    """Load chain-of-thought rationales generated by the separate CoT pipeline step, if any.

    Returns:
        A mapping of window id to rationale text, or an empty mapping when
        :data:`_RATIONALES_ENV` is unset or names a missing file.
    """
    path = os.environ.get(_RATIONALES_ENV)
    if not path or not Path(path).exists():
        return {}
    with Path(path).open(encoding="utf-8") as handle:
        return json.load(handle)


def _timestamp_to_us(timestamp: "pd.Timestamp") -> int:
    """Convert a naive UTC-equivalent pandas timestamp to whole microseconds.

    Args:
        timestamp: A naive UTC-equivalent timestamp.

    Returns:
        Nanoseconds-since-epoch divided down to microseconds.
    """
    return int(timestamp.value // 1_000)


def _periodicity_score(values: np.ndarray) -> float | None:
    """Score how strongly periodic a value sequence is, via its normalized autocorrelation peak.

    Mean and standard deviation describe level and spread, but say nothing about whether a channel
    is oscillating -- two windows with identical mean/std can be a clean sine wave and a flatlined
    signal that has stopped oscillating (itself often the anomalous condition). This computes the
    linear autocorrelation via FFT (fast enough for a 24-hour, ~3,000-point context window) and
    returns its highest peak past a small excluded lag, normalized so 1.0 is perfectly periodic and
    0.0 is white noise.

    Args:
        values: The sequence to score. Assumed roughly evenly spaced; ESA-AD's ~30s median cadence
            makes this a reasonable approximation for a periodicity estimate, not an exact spectral
            analysis.

    Returns:
        The peak normalized autocorrelation past the excluded lag, or ``None`` if there are too few
        points (:data:`_MIN_PERIODICITY_POINTS`) or the sequence is constant (zero variance).
    """
    n = len(values)
    if n < _MIN_PERIODICITY_POINTS:
        return None
    centered = values.astype(np.float64) - values.mean()
    if centered.std() < _ZERO_VARIANCE_TOLERANCE:
        return None
    nfft = 1
    while nfft < 2 * n:
        nfft *= 2
    spectrum = np.fft.rfft(centered, n=nfft)
    autocorr = np.fft.irfft(spectrum * np.conj(spectrum), n=nfft)[:n]
    autocorr /= autocorr[0]
    exclude = max(2, n // 50)  # skip the trivial near-zero-lag decay
    if len(autocorr) <= exclude + 2:
        return None
    return round(float(autocorr[exclude:].max()), 3)


def _window_annotations(
    ref: "ESAWindowRef",
    window_periodicity: float | None,
    context_periodicity: float | None,
    minutes_since_command: float | None,
) -> list[Annotation]:
    """Build the fixed and optional annotations for one window's record.

    Args:
        ref: The window reference the record is built from.
        window_periodicity: The window's own periodicity score, or ``None`` (see
            :func:`_periodicity_score`).
        context_periodicity: The surrounding 24-hour context's periodicity score, or ``None``.
        minutes_since_command: Minutes since the most recent priority>=2 telecommand before the
            window's reference point, or ``None`` (see :func:`_minutes_since_command`).

    Returns:
        The annotations to attach to the record.
    """
    annotations = [
        Annotation(key="channel", value=ref.channel, id=f"{ref.window_id}-channel"),
        Annotation(key="label", value=ref.label, id=f"{ref.window_id}-label"),
        Annotation(key="split", value=ref.split, id=f"{ref.window_id}-split"),
        Annotation(key="anomaly_id", value=ref.anomaly_id, id=f"{ref.window_id}-anomaly-id"),
    ]
    if ref.category is not None:
        annotations.append(Annotation(key="category", value=ref.category, id=f"{ref.window_id}-category"))
    if ref.anomaly_class is not None:
        annotations.append(Annotation(key="class", value=ref.anomaly_class, id=f"{ref.window_id}-class"))
    if window_periodicity is not None:
        annotations.append(
            Annotation(key="window_periodicity", value=window_periodicity, id=f"{ref.window_id}-window-periodicity")
        )
    if context_periodicity is not None:
        annotations.append(
            Annotation(key="context_periodicity", value=context_periodicity, id=f"{ref.window_id}-context-periodicity")
        )
    if minutes_since_command is not None:
        annotations.append(
            Annotation(
                key="minutes_since_command", value=minutes_since_command, id=f"{ref.window_id}-minutes-since-command"
            )
        )
    return annotations


def _periodicity_pair(
    values: np.ndarray, series: "pd.Series", window_start: "pd.Timestamp"
) -> tuple[float | None, float | None]:
    """Score periodicity both for a window and for its surrounding 24-hour context.

    Args:
        values: The window's own values (already sliced).
        series: The full channel series, to slice the wider context from.
        window_start: The window's start timestamp.

    Returns:
        ``(window_periodicity, context_periodicity)``, either possibly ``None`` (see
        :func:`_periodicity_score`).
    """
    pd = _import_pandas()
    context_start = window_start - pd.Timedelta(microseconds=_CONTEXT_BEFORE_US)
    context_end = context_start + pd.Timedelta(microseconds=_CONTEXT_LEN_US)
    context = series[(series.index >= context_start) & (series.index < context_end)]
    return _periodicity_score(values), _periodicity_score(context.to_numpy(dtype=np.float32))


def _load_telecommand_executions(source_dir: Path, cache_dir: Path) -> np.ndarray:
    """Load every priority>=2 telecommand's execution timestamps into one sorted array.

    Args:
        source_dir: The local ESA-AD Mission1 directory.
        cache_dir: The connector's cache directory for this build.

    Returns:
        Every qualifying execution, as naive UTC-equivalent Unix microseconds (see module
        docstring), sorted ascending. Empty if ``telecommands.csv`` or the ``telecommands/``
        directory isn't present under ``source_dir``.
    """
    pd = _import_pandas()
    meta_path = source_dir / "telecommands.csv"
    telecommands_dir = source_dir / "telecommands"
    if not meta_path.exists() or not telecommands_dir.exists():
        return np.array([], dtype=np.int64)

    meta = pd.read_csv(meta_path)
    names = meta.loc[meta["Priority"] >= _TELECOMMAND_MIN_PRIORITY, "Telecommand"]

    all_executions: list[np.ndarray] = []
    for name in names:
        zip_path = telecommands_dir / f"{name}.zip"
        if not zip_path.exists():
            continue
        dest = cache_dir / f"tc-{name}"
        if not dest.exists():
            with zipfile.ZipFile(zip_path) as archive:
                archive.extract(name, path=cache_dir)
            (cache_dir / name).rename(dest)
        index = pd.read_pickle(dest).index
        all_executions.append(np.asarray(index.view("int64")) // 1_000)
    if not all_executions:
        return np.array([], dtype=np.int64)
    return np.sort(np.concatenate(all_executions))


def _minutes_since_command(reference_us: int, sorted_command_us: np.ndarray) -> float | None:
    """Find how long before ``reference_us`` the most recent qualifying telecommand executed.

    Backward-only (causal): a command that executed after the reference point cannot have caused
    whatever happens at or after it.

    Args:
        reference_us: The window's reference point (its anomalous start, or the matching offset
            into a nominal window), in naive UTC-equivalent Unix microseconds.
        sorted_command_us: Every qualifying execution, ascending (see
            :func:`_load_telecommand_executions`).

    Returns:
        Minutes since the most recent prior execution, or ``None`` if there isn't one within
        :data:`_TELECOMMAND_LOOKBACK_US`.
    """
    if len(sorted_command_us) == 0:
        return None
    idx = np.searchsorted(sorted_command_us, reference_us, side="right")
    if idx == 0:
        return None
    delta_us = reference_us - sorted_command_us[idx - 1]
    if delta_us > _TELECOMMAND_LOOKBACK_US:
        return None
    return round(delta_us / 60_000_000, 1)


class ESAMission1Subsystem5Connector(BaseConnector[ESAWindowRef]):
    """Six-hour ESA-AD Mission1 subsystem_5 windows, labeled nominal or anomalous."""

    def download(self, cache_dir: Path) -> list[ESAWindowRef]:  # noqa: PLR6301 (override: BaseConnector's contract requires an instance method)
        """Extract the six subsystem_5 channels and build one window reference per labeled interval.

        Also builds one matched nominal window per labeled interval, sampled from the same channel
        and split half, clear of every labeled interval on that channel.

        Args:
            cache_dir: Directory to extract channel pickles into (created by the engine).

        Returns:
            Two :class:`ESAWindowRef` per labeled ``Anomaly``/``Rare Event`` interval: one
            anomalous, one nominal. ``Communication Gap`` and ``Invalid Segment`` intervals are
            excluded from the pairing (see module docstring) but still guard nominal sampling.

        Raises:
            FileNotFoundError: If the source directory named by ``ESA_MISSION1_DIR`` (or the shared
                hackathon default) does not exist.
        """
        pd = _import_pandas()
        source_dir = _source_dir()
        if not source_dir.exists():
            raise FileNotFoundError(
                f"ESA-AD Mission1 source not found at {source_dir}. Set {_SOURCE_DIR_ENV} to its path"
            )

        channel_paths = {channel: _extract_channel(source_dir, cache_dir, channel) for channel in _CHANNELS}
        labels = _load_labels(source_dir)

        rng = np.random.default_rng(_SEED)
        refs: list[ESAWindowRef] = []
        for channel in _CHANNELS:
            channel_labels = labels[labels["Channel"] == channel]
            channel_index = pd.read_pickle(channel_paths[channel]).index
            channel_span = (_timestamp_to_us(channel_index[0]), _timestamp_to_us(channel_index[-1]))
            # Guard nominal sampling against every labeled interval, including the excluded
            # categories: a "nominal" window must not silently overlap missing or invalid data.
            guarded_intervals_us = [
                (
                    _timestamp_to_us(row.StartTime) - _OVERLAP_GUARD_US,
                    _timestamp_to_us(row.EndTime) + _OVERLAP_GUARD_US,
                )
                for row in channel_labels.itertuples(index=False)
            ]
            pairable_labels = channel_labels[~channel_labels["Category"].isin(_EXCLUDED_CATEGORIES)]

            for occurrence, row in enumerate(pairable_labels.itertuples(index=False)):
                # The same anomaly ID can recur as several distinct, non-contiguous intervals on one
                # channel (a periodic event, for example), so (ID, channel) alone is not unique.
                split = _split_for(row.StartTime)
                anomaly_start_us = _timestamp_to_us(row.StartTime)
                anomaly_id = f"{row.ID}-{channel}-{occurrence}"

                refs.append(
                    ESAWindowRef(
                        window_id=f"{anomaly_id}-pos",
                        channel=channel,
                        channel_path=channel_paths[channel],
                        window_start_us=anomaly_start_us - _WINDOW_BEFORE_US,
                        label="anomalous",
                        category=row.Category,
                        anomaly_class=row.Class,
                        anomaly_id=row.ID,
                        split=split,
                    )
                )
                nominal_start_us = _sample_nominal_start_us(rng, channel_span, guarded_intervals_us)
                refs.append(
                    ESAWindowRef(
                        window_id=f"{anomaly_id}-neg",
                        channel=channel,
                        channel_path=channel_paths[channel],
                        window_start_us=nominal_start_us,
                        label="nominal",
                        category=None,
                        anomaly_class=None,
                        anomaly_id=row.ID,
                        split=split,
                    )
                )
        return refs

    def convert(self, raw_refs: list[ESAWindowRef]) -> TimeFDataset:
        """Slice each window's values from its channel and build the labeled records and tasks.

        Args:
            raw_refs: The window references from :meth:`download`.

        Returns:
            One record per window, each with a single-channel irregular time series, its label,
            split, and periodicity annotations, and one :class:`~timenet.types.AnswerTask`.
        """
        pd = _import_pandas()
        dataset = TimeFDataset(metadata=self.metadata())
        rationales = _load_rationales()
        channel_cache: dict[Path, pd.Series] = {}
        command_times = (
            _load_telecommand_executions(_source_dir(), raw_refs[0].channel_path.parent)
            if raw_refs
            else np.array([], dtype=np.int64)
        )

        def load_channel(path: Path) -> "pd.Series":
            if path not in channel_cache:
                channel_cache[path] = pd.read_pickle(path).iloc[:, 0]
            return channel_cache[path]

        for ref in raw_refs:
            series = load_channel(ref.channel_path)
            window_start = pd.Timestamp(ref.window_start_us, unit="us")
            window = series[
                (series.index >= window_start)
                & (series.index < window_start + pd.Timedelta(microseconds=_WINDOW_LEN_US))
            ]
            if window.empty:
                continue

            values = window.to_numpy(dtype=np.float32)
            offsets_us = ((window.index - window.index[0]).total_seconds() * 1_000_000).to_numpy().astype(np.int64)
            periodicity = _periodicity_pair(values, series, window_start)
            time_series = TimeSeries.from_irregular(
                values,
                time_offsets_us=offsets_us,
                spec=_spec_for(ref.channel),
                signal=ref.channel,
                source_id=ref.channel,
                time_series_id=f"ts-{ref.window_id}",
            )
            record = dataset.add_record(
                time_series=(time_series,),
                record_id=ref.window_id,
                start_time=_timestamp_to_us(window.index[0]),
            )
            record.add_annotations(
                _window_annotations(
                    ref, *periodicity, _minutes_since_command(ref.window_start_us + _WINDOW_BEFORE_US, command_times)
                )
            )

            rationale = rationales.get(ref.window_id)
            answer = rationale if rationale is not None else f"Answer: {ref.label}"
            dataset.add_task(
                record,
                AnswerTask(
                    prompt=_QUESTION,
                    target=answer,
                    rationale=rationale,
                    id=f"task-{ref.window_id}",
                ),
            )
        return dataset


CONNECTOR = ESAMission1Subsystem5Connector
